console.log(a%b); // modulus operator gives the remainder of the division of a by b

console.log(100%2);
console.log(101%2);
console.log(103%2);

//if n%2==0 then n is even else(n%2==1) n is odd


console.log(a**b); //exponentiation operator gives the result of raising a to the power of b a^b
console.log(2**3); // 2 raised to the power of 3 is 8

//increment and decrement operator
a++; // post-increment operator increases the value of a by 1 after the current expression is evaluated
console.log(a); // 11
++a; // pre-increment operator increases the value of a by 1 before the current expression is evaluated
console.log(a); // 12   

b--; // post-decrement operator decreases the value of b by 1 after the current expression is evaluated
console.log(b); // 2
--b; // pre-decrement operator decreases the value of b by 1 before the current expression is evaluated
console.log(b); // 3


