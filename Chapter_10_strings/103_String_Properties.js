//String properties and basic access
let str = "Hello World";
//length start from 1 
console.log(str.length);

//Access by index
console.log(str[0]);
console.log(str[6]);
console.log(str.at(-1));
console.log(str.at(-5));

// charAt()
str.charAt(0);   // "H"
// charCodeAt() — Unicode value
str.charCodeAt(0);  // 72